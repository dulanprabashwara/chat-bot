"use client";
import { cn } from "@/lib/utils";
import { IconMenu2, IconX } from "@tabler/icons-react";
import {
  motion,
  AnimatePresence,
  useScroll,
  useMotionValueEvent,
} from "motion/react";

import React, { useRef, useState, useEffect } from "react";

export const Navbar = ({ children, className }) => {
  const ref = useRef(null);
  const { scrollY } = useScroll();
  const [visible, setVisible] = useState(false);
  const [isClient, setIsClient] = useState(false);

  // Ensure we're on the client side and set initial scroll state
  useEffect(() => {
    setIsClient(true);
    const handleInitialScroll = () => {
      const currentScrollY = window.scrollY || window.pageYOffset || 0;
      setVisible(currentScrollY > 100);
    };

    handleInitialScroll();

    // Also check after a small delay to ensure everything is loaded
    const timeoutId = setTimeout(handleInitialScroll, 100);

    return () => clearTimeout(timeoutId);
  }, []);

  useMotionValueEvent(scrollY, "change", (latest) => {
    if (!isClient) return;

    if (latest > 100) {
      setVisible(true);
    } else {
      setVisible(false);
    }
  });

  return (
    <motion.div
      ref={ref}
      className={cn("fixed inset-x-0 top-0 z-40 w-full", className)}
    >
      {React.Children.map(children, (child) =>
        React.isValidElement(child)
          ? React.cloneElement(child, { visible: isClient ? visible : false })
          : child
      )}
    </motion.div>
  );
};

