export const NavItems = ({ items, className, onItemClick, visible }) => {
  const [hovered, setHovered] = useState(null);

  return (
    <motion.div
      onMouseLeave={() => setHovered(null)}
      animate={{
        gap: visible ? "8px" : "24px",
      }}
      transition={{ duration: 0.3 }}
      className={cn(
        "hidden flex-1 flex-row items-center justify-center text-xl font-medium text-zinc-600 transition duration-200 hover:text-zinc-800 lg:flex",
        className
      )}
      style={{
        gap: visible ? "8px" : "24px",
      }}
    >
      {items.map((item, idx) => (
        <a
          onMouseEnter={() => setHovered(idx)}
          onClick={onItemClick}
          className="relative text-neutral-600 dark:text-neutral-300 font-semibold transition-all whitespace-nowrap px-6 py-3 text-xl"
          key={`link-${idx}`}
          href={item.link}
        >
          {hovered === idx && (
            <motion.div
              layoutId="hovered"
              className="absolute inset-0 h-full w-full rounded-lg bg-gray-100 dark:bg-neutral-800"
            />
          )}
          <span className="relative z-20">{item.name}</span>
        </a>
      ))}
    </motion.div>
  );
};

